// Generates src/worldmap.js: a pixel land mask + one anchor point per country (ISO 3166 alpha-2).
// Dev-only. Run from repo root after: npm i --no-save world-atlas@2 topojson-client@3 d3-geo@3 i18n-iso-countries@7
//   node tools/gen-worldmap.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';

const require = createRequire(import.meta.url);
const countries = require('i18n-iso-countries');
const load = name => JSON.parse(readFileSync(require.resolve(`world-atlas/${name}`), 'utf8'));

// Equirectangular grid, 3.75° cells, latitude cropped to 84°N … 58.5°S (no Antarctica).
const CELL = 3.75, LON0 = -180, LAT0 = 84, COLS = 96, ROWS = 38;

const land = feature(load('land-110m.json'), load('land-110m.json').objects.land);
const bits = [];
for (let r = 0; r < ROWS; r++) {
  for (let c = 0; c < COLS; c++) {
    // A cell is land when any of 4 sample points falls on land.
    let hit = false;
    for (const [dx, dy] of [[0.25, 0.25], [0.75, 0.25], [0.25, 0.75], [0.75, 0.75]]) {
      if (geoContains(land, [LON0 + (c + dx) * CELL, LAT0 - (r + dy) * CELL])) { hit = true; break; }
    }
    bits.push(hit ? 1 : 0);
  }
}
// Pack 6 bits per char (base64url alphabet) to keep the file small.
const ALPHA = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';
let mask = '';
for (let i = 0; i < bits.length; i += 6) {
  let v = 0;
  for (let j = 0; j < 6; j++) v = (v << 1) | (bits[i + j] || 0);
  mask += ALPHA[v];
}

// Anchor = centroid of the country's largest polygon (France -> mainland, US -> lower 48).
const topo = load('countries-50m.json');
const anchors = {};
const sizes = {};
for (const f of feature(topo, topo.objects.countries).features) {
  const a2 = f.id && countries.numericToAlpha2(f.id);
  if (!a2) continue;
  const polys = f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates : [f.geometry.coordinates];
  // Planar area/centroid of the outer ring: winding-independent and accurate enough to place a flag.
  let best = null;
  for (const coords of polys) {
    let ring = coords[0];
    // Rings crossing the antimeridian (Russia, Fiji) are unwrapped to continuous longitudes first.
    const lons = ring.map(p => p[0]);
    if (Math.max(...lons) - Math.min(...lons) > 180) ring = ring.map(([x, y]) => [x < 0 ? x + 360 : x, y]);
    let a = 0, cx = 0, cy = 0;
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const cross = ring[j][0] * ring[i][1] - ring[i][0] * ring[j][1];
      a += cross; cx += (ring[j][0] + ring[i][0]) * cross; cy += (ring[j][1] + ring[i][1]) * cross;
    }
    if (a === 0) continue;
    const area = Math.abs(a / 2);
    if (!best || area > best.area) best = { area, lon: cx / (3 * a), lat: cy / (3 * a) };
  }
  if (!best) continue;
  // Several features can share one code (e.g. Ashmore and Cartier Is. = AU); keep the largest.
  if (sizes[a2] >= best.area) continue;
  sizes[a2] = best.area;
  const lon = best.lon > 180 ? best.lon - 360 : best.lon, lat = best.lat;
  anchors[a2] = [Math.round(lon * 10) / 10, Math.round(lat * 10) / 10];
}

const out = `/* Generated by tools/gen-worldmap.mjs from Natural Earth (public domain) via world-atlas. Do not edit. */
window.KOMARI_WORLDMAP = ${JSON.stringify({ cell: CELL, lon0: LON0, lat0: LAT0, cols: COLS, rows: ROWS, mask, anchors })};
`;
writeFileSync(new URL('../src/worldmap.js', import.meta.url), out);
console.log(`land cells ${bits.filter(Boolean).length}/${bits.length}, anchors ${Object.keys(anchors).length}, bytes ${out.length}`);
